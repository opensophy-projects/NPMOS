// WAF -> Agent: settings of the open-appsec agent and its advanced ML model.
// Settings are stored in npmos_setting ("waf.agent") and written to npmos-agent.env next to the
// policy (volume appsec-localconfig); the agent's entrypoint (deploy/openappsec/agent/npmos-entry.sh)
// applies them at start and copies the file to npmos-agent.applied. Saving restarts the agent.
// The advanced model is the .tgz the upstream entrypoint unpacks from /advanced-model at start.
import { createWriteStream } from "node:fs";
import { mkdir, open, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { pipeline } from "node:stream/promises";
import internalAuditLog from "../../internal/audit-log.js";
import errs from "../../lib/error.js";
import { debug, global as logger } from "../../logger.js";
import control from "../control/client.js";
import { getSetting, setSetting } from "../settings.js";

const LOCALCONFIG_DIR = path.dirname(process.env.NPMOS_APPSEC_POLICY_FILE || "/ext/appsec/local_policy.yaml");
const ENV_FILE = path.join(LOCALCONFIG_DIR, "npmos-agent.env");
const APPLIED_FILE = path.join(LOCALCONFIG_DIR, "npmos-agent.applied");
const MODEL_DIR = process.env.NPMOS_APPSEC_MODEL_DIR || "/ext/appsec-model";
const MODEL_FILE = path.join(MODEL_DIR, "open-appsec-advanced-model.tgz");
const MODEL_MAX_BYTES = 1024 * 1024 * 1024;
const AGENT_SERVICE = "appsec-agent";

const renderEnv = (s) =>
	[
		"# Generated by NPMOS (WAF -> Agent), applied by the agent at start. Manual changes are overwritten.",
		`CROWDSEC_ENABLED=${s.crowdsec.enabled}`,
		`CROWDSEC_MODE=${s.crowdsec.mode}`,
		`NPMOS_FAIL_OPEN=${s.failOpen.enabled}`,
		`NPMOS_FAIL_OPEN_TIMEOUT_MS=${s.failOpen.timeoutMs}`,
		"",
	].join("\n");

const readText = async (file) => {
	try {
		return await readFile(file, "utf8");
	} catch {
		return null;
	}
};

const writeEnv = async (settings) => {
	await mkdir(LOCALCONFIG_DIR, { recursive: true });
	const tmp = `${ENV_FILE}.tmp`;
	await writeFile(tmp, renderEnv(settings));
	await rename(tmp, ENV_FILE);
};

const getModel = async () => {
	try {
		const s = await stat(MODEL_FILE);
		return { present: true, size: s.size, modifiedOn: s.mtime.toISOString() };
	} catch {
		return { present: false };
	}
};

const state = async (settings) => {
	const applied = await readText(APPLIED_FILE);
	return {
		...settings,
		// null: the agent has not started with NPMOS settings yet (older image or never restarted)
		restartRequired: applied === null ? null : applied !== renderEnv(settings),
		model: await getModel(),
	};
};

/** at backend start: the agent reads the file at its next start */
const bootstrap = async () => {
	try {
		const settings = await getSetting("waf.agent");
		if ((await readText(ENV_FILE)) !== renderEnv(settings)) {
			await writeEnv(settings);
		}
	} catch (err) {
		logger.error(`WAF agent settings: ${err.message}`);
		debug(logger, err);
	}
};

const restartAgent = (access) => control.restartService(AGENT_SERVICE, access.token.getUserId(1));

const internalWafAgent = {
	/**
	 * @param {Access} access
	 */
	get: async (access) => {
		await access.can("npmos_services:list");
		return state(await getSetting("waf.agent"));
	},

	/**
	 * @param {Access}  access
	 * @param {{crowdsec: {enabled, mode}, failOpen: {enabled, timeout_ms}}} data
	 * @param {boolean} [apply]  restart the agent now
	 */
	set: async (access, data, apply = true) => {
		await access.can("npmos_services:manage");
		const settings = await setSetting("waf.agent", {
			crowdsec: { enabled: data.crowdsec.enabled, mode: data.crowdsec.mode },
			failOpen: { enabled: data.fail_open.enabled, timeoutMs: data.fail_open.timeout_ms },
		});
		await writeEnv(settings);
		await internalAuditLog.add(access, {
			action: "updated",
			object_type: "waf",
			meta: { name: "open-appsec agent", ...settings },
		});
		if (apply) {
			await restartAgent(access);
		}
		return { ...(await state(settings)), restarting: apply };
	},

	/**
	 * Streams the uploaded .tgz (request body) to the model volume; the agent unpacks it at start.
	 * @param {Access}          access
	 * @param {import("express").Request} req
	 * @param {boolean}         [apply]  restart the agent now
	 */
	uploadModel: async (access, req, apply = true) => {
		await access.can("npmos_services:manage");
		const length = Number(req.headers["content-length"] || 0);
		if (length > MODEL_MAX_BYTES) {
			throw new errs.ValidationError("The model file is larger than 1 GB");
		}
		await mkdir(MODEL_DIR, { recursive: true });
		const tmp = `${MODEL_FILE}.upload`;
		let size = 0;
		req.on("data", (chunk) => {
			size += chunk.length;
			if (size > MODEL_MAX_BYTES) req.destroy(new Error("The model file is larger than 1 GB"));
		});
		try {
			await pipeline(req, createWriteStream(tmp, { mode: 0o644 }));
			const handle = await open(tmp, "r");
			const magic = Buffer.alloc(2);
			await handle.read(magic, 0, 2, 0);
			await handle.close();
			if (size === 0 || magic[0] !== 0x1f || magic[1] !== 0x8b) {
				throw new errs.ValidationError("The model must be a .tgz file (open-appsec-advanced-model.tgz)");
			}
			await rename(tmp, MODEL_FILE);
		} catch (err) {
			await rm(tmp, { force: true });
			throw err instanceof errs.ValidationError ? err : new errs.ValidationError(err.message);
		}
		await internalAuditLog.add(access, {
			action: "updated",
			object_type: "waf",
			meta: { name: "open-appsec advanced model", size },
		});
		if (apply) {
			await restartAgent(access);
		}
		return { ...(await getModel()), restarting: apply };
	},
};

export { bootstrap };
export default internalWafAgent;
