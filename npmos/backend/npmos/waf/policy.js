// open-appsec declarative policy (local_policy.yaml, syntax v1beta1 as in open-appsec-npm).
//
// The source of truth is the database (npmos_waf_host / npmos_waf_location); the file is
// generated from it on every change of a proxy host or of its WAF settings and is never edited
// by hand. Names of the generated objects are the same as in open-appsec-npm
// (npm-managed-*-proxyhost-<id>), so an installation of open-appsec-npm is imported as is.
//
// The agent sees the file through the shared volume (/ext/appsec in both containers, symlinked by
// the agent to /etc/cp/conf/local_policy.yaml). After a write NPMOS asks the agent to apply it
// (set-apply-policy on its local REST port, the agent shares the network namespace of npmos);
// autoPolicyLoad in the agent picks the change up within 30 s anyway.
import { mkdir, readdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import _ from "lodash";
import YAML from "yaml";
import db from "../../db.js";
import { debug, global as logger } from "../../logger.js";
import { getCurrentCustom, mergeCustom, parseCustom } from "./custom.js";

const POLICY_FILE = process.env.NPMOS_APPSEC_POLICY_FILE || "/ext/appsec/local_policy.yaml";
const BACKUP_DIR = "/data/npmos/waf/policy-backups";
const BACKUPS_KEPT = 20;
const AGENT_URL = process.env.NPMOS_APPSEC_ORCHESTRATION_URL || "http://127.0.0.1:7777";
const AGENT_POLICY_PATH = "/etc/cp/conf/local_policy.yaml";
const APPLY_TIMEOUT_MS = 3000;
const DEBOUNCE_MS = 1000;

const HEADER =
	"# Generated by NPMOS from its database (WAF settings of proxy hosts). Manual changes are overwritten.\n";

const MODES = ["detect-learn", "prevent-learn"];
const CONFIDENCES = ["medium", "high", "critical"];

const DEFAULT_TRIGGER = "appsec-default-log-trigger";
const DEFAULT_PRACTICE = "webapp-default-practice";
const DEFAULT_RESPONSE = "appsec-default-web-user-response";

const names = (hostId, locationIndex) => {
	const suffix = locationIndex === undefined ? `${hostId}` : `${hostId}-${locationIndex}`;
	return {
		rule: `npm-managed-specific-rule-proxyhost-${suffix}`,
		practice: `npm-managed-practice-proxyhost-${suffix}`,
		trigger: `npm-managed-log-trigger-proxyhost-${suffix}`,
	};
};

// The default policy of open-appsec-npm (deployment/local_policy.yaml): everything not covered by
// a specific rule is inactive. Logs go to the agent's stdout/log files only, never to the cloud.
const basePolicy = () => ({
	policies: {
		default: {
			triggers: [DEFAULT_TRIGGER],
			mode: "inactive",
			practices: [DEFAULT_PRACTICE],
			"custom-response": DEFAULT_RESPONSE,
		},
		"specific-rules": [],
	},
	practices: [practice(DEFAULT_PRACTICE, "inactive", "high")],
	"log-triggers": [logTrigger(DEFAULT_TRIGGER)],
	"custom-responses": [{ name: DEFAULT_RESPONSE, mode: "response-code-only", "http-response-code": 403 }],
});

function practice(name, mode, minimumConfidence) {
	return {
		name,
		"web-attacks": {
			"max-body-size-kb": 1000000,
			"max-header-size-bytes": 102400,
			"max-object-depth": 40,
			"max-url-size-bytes": 32768,
			"minimum-confidence": minimumConfidence,
			"override-mode": mode,
			protections: {
				"csrf-protection": "inactive",
				"error-disclosure": "inactive",
				"non-valid-http-methods": false,
				"open-redirect": "inactive",
			},
		},
		"anti-bot": { "injected-URIs": [], "validated-URIs": [], "override-mode": "inactive" },
		"snort-signatures": { configmap: [], "override-mode": "inactive" },
		"openapi-schema-validation": { configmap: [], "override-mode": "inactive" },
	};
}

function logTrigger(name) {
	return {
		name,
		"access-control-logging": { "allow-events": false, "drop-events": true },
		"additional-suspicious-events-logging": {
			enabled: true,
			"minimum-severity": "high",
			"response-body": false,
			"response-code": true,
		},
		"appsec-logging": { "all-web-requests": false, "detect-events": true, "prevent-events": true },
		"extended-logging": { "http-headers": false, "request-body": false, "url-path": true, "url-query": true },
		"log-destination": { cloud: false, stdout: { format: "json" } },
	};
}

/**
 * Adds a specific rule per domain name (v1beta1 takes one host per rule), with its own practice
 * and log trigger.
 */
const addRules = (policy, n, hosts, mode, minimumConfidence) => {
	hosts.forEach((host, index) => {
		policy.policies["specific-rules"].push({
			host,
			name: index > 0 ? `${n.rule}.${index}` : n.rule,
			triggers: [n.trigger],
			mode,
			practices: [n.practice],
			"custom-response": DEFAULT_RESPONSE,
		});
	});
	policy.practices.push(practice(n.practice, mode, minimumConfidence));
	policy["log-triggers"].push(logTrigger(n.trigger));
};

const parseJson = (value) => (typeof value === "string" ? JSON.parse(value) : value) || [];

/**
 * @param   {{custom?: object}} [options]  parsed expert fragment instead of the one in force
 * @returns {Promise<{policy: object, hosts: number, customId: number|null}>}
 */
const buildPolicy = async ({ custom } = {}) => {
	const knex = db();
	const proxyHosts = await knex("proxy_host")
		.select("id", "domain_names", "locations")
		.where({ is_deleted: 0, enabled: 1 })
		.orderBy("id");
	const hostRows = _.keyBy(await knex("npmos_waf_host").select(), "proxy_host_id");
	const locationRows = _.groupBy(await knex("npmos_waf_location").select(), "proxy_host_id");

	const policy = basePolicy();
	let hosts = 0;
	for (const proxyHost of proxyHosts) {
		const domains = parseJson(proxyHost.domain_names);
		const locations = parseJson(proxyHost.locations);
		const host = hostRows[proxyHost.id];
		if (host?.enabled) {
			addRules(policy, names(proxyHost.id), domains, host.mode, host.minimum_confidence);
			hosts++;
		}
		// locations are numbered by their position in the host, as in open-appsec-npm
		for (const location of locationRows[proxyHost.id] || []) {
			const index = locations.findIndex((l) => l.path === location.path);
			if (index === -1) {
				continue;
			}
			addRules(
				policy,
				names(proxyHost.id, index),
				domains.map((domain) => `${domain}${location.path}`),
				location.enabled ? location.mode : "inactive",
				location.minimum_confidence,
			);
		}
	}
	if (custom) {
		return { policy: mergeCustom(policy, custom), hosts, customId: null };
	}
	const current = await getCurrentCustom();
	if (!current) {
		return { policy, hosts, customId: null };
	}
	try {
		const parsed = parseCustom(current.content);
		if (!Object.keys(parsed).length) {
			return { policy, hosts, customId: null };
		}
		return { policy: mergeCustom(policy, parsed), hosts, customId: current.id };
	} catch (err) {
		// validated when saved; only a hand-edited database gets here
		logger.error(`WAF: expert policy version ${current.id} is not applied: ${err.message}`);
		return { policy, hosts, customId: null };
	}
};

const CUSTOM_HEADER = "# + expert fragments (WAF -> Policy), merged over the generated rules.\n";

const render = (policy, withCustom = false) =>
	`${HEADER}${withCustom ? CUSTOM_HEADER : ""}${YAML.stringify(policy, { lineWidth: 0 })}`;

const readPolicyFile = async () => {
	try {
		return await readFile(POLICY_FILE, "utf8");
	} catch (err) {
		if (err.code === "ENOENT") {
			return null;
		}
		throw err;
	}
};

const backup = async (content, label) => {
	await mkdir(BACKUP_DIR, { recursive: true });
	const stamp = new Date().toISOString().replace(/[:.]/g, "-");
	await writeFile(`${BACKUP_DIR}/local_policy-${stamp}${label ? `-${label}` : ""}.yaml`, content, { mode: 0o600 });
	const files = (await readdir(BACKUP_DIR)).filter((f) => f.startsWith("local_policy-")).sort();
	for (const old of files.slice(0, Math.max(0, files.length - BACKUPS_KEPT))) {
		await rm(`${BACKUP_DIR}/${old}`, { force: true });
	}
};

// written in place of the old file by rename, so the agent never reads a half-written policy
const writeAtomic = async (content) => {
	await mkdir(dirname(POLICY_FILE), { recursive: true });
	const tmp = `${POLICY_FILE}.npmos-tmp`;
	await writeFile(tmp, content, { mode: 0o644 });
	await rename(tmp, POLICY_FILE);
};

const state = {
	generatedAt: null,
	hosts: 0,
	applied: null,
};

/**
 * Asks the agent to apply the policy now. Not reaching the agent is not an error of the change:
 * it applies the file at its next start or within 30 s (autoPolicyLoad).
 */
const notifyAgent = async () => {
	try {
		const response = await fetch(`${AGENT_URL}/set-apply-policy`, {
			method: "POST",
			headers: { "Content-Type": "application/json" },
			body: JSON.stringify({ policy_path: AGENT_POLICY_PATH }),
			signal: AbortSignal.timeout(APPLY_TIMEOUT_MS),
		});
		state.applied = {
			ok: response.ok,
			at: new Date().toISOString(),
			error: response.ok ? null : `HTTP ${response.status}`,
		};
	} catch (err) {
		state.applied = { ok: false, at: new Date().toISOString(), error: err.cause?.code || err.message };
	}
	if (!state.applied.ok) {
		logger.warn(`WAF policy written, the agent was not notified (${state.applied.error})`);
	}
	return state.applied;
};

/**
 * Generates local_policy.yaml from the database; writes it (with a backup of the previous
 * version) and notifies the agent only if it changed, unless forced.
 * @param   {{force?: boolean}} [options]
 * @returns {Promise<{changed: boolean, hosts: number}>}
 */
const regenerate = async ({ force = false } = {}) => {
	const { policy, hosts, customId } = await buildPolicy();
	const content = render(policy, customId !== null);
	const current = await readPolicyFile();
	const changed = current !== content;
	if (changed) {
		if (current !== null) {
			await backup(current);
		}
		await writeAtomic(content);
		logger.info(`WAF policy generated: ${hosts} protected host(s)`);
	}
	state.generatedAt = new Date().toISOString();
	state.hosts = hosts;
	if (changed || force) {
		await notifyAgent();
	}
	return { changed, hosts };
};

// one generation at a time; a burst of changes (e.g. regenerating all hosts) ends in one write
let timer = null;
let running = Promise.resolve();
const scheduleRegenerate = () => {
	clearTimeout(timer);
	timer = setTimeout(() => {
		running = running
			.then(() => regenerate())
			.catch((err) => logger.error(`WAF policy generation failed: ${err.message}`));
	}, DEBOUNCE_MS);
	timer.unref?.();
};

/**
 * Regenerates now (waits for a pending scheduled run first).
 * @param {{force?: boolean}} [options]
 */
const regenerateNow = (options) => {
	clearTimeout(timer);
	const result = running.then(() => regenerate(options));
	running = result.catch(() => {});
	return result;
};

/**
 * Migration from open-appsec-npm: if NPMOS has no WAF settings yet, takes them from the
 * npm-managed-* rules of an existing local_policy.yaml. The original file is kept in the backups.
 * @param {string} content
 */
const importLegacy = async (content) => {
	let policy;
	try {
		policy = YAML.parse(content);
	} catch (err) {
		logger.warn(`WAF: existing local_policy.yaml is not valid YAML, not imported (${err.message})`);
		return 0;
	}
	const rules = policy?.policies?.["specific-rules"];
	if (!Array.isArray(rules)) {
		return 0;
	}
	const practices = _.keyBy(Array.isArray(policy.practices) ? policy.practices : [], "name");
	const knex = db();
	const now = new Date();
	let imported = 0;
	for (const rule of rules) {
		const match = /^npm-managed-specific-rule-proxyhost-(\d+)(?:-(\d+))?$/.exec(rule?.name || "");
		if (!match) {
			continue;
		}
		const hostId = Number.parseInt(match[1], 10);
		const proxyHost = await knex("proxy_host")
			.select("id", "locations")
			.where({ id: hostId, is_deleted: 0 })
			.first();
		if (!proxyHost) {
			continue;
		}
		const enabled = MODES.includes(rule.mode);
		const confidence = practices[rule.practices?.[0]]?.["web-attacks"]?.["minimum-confidence"];
		const values = {
			enabled,
			mode: enabled ? rule.mode : "detect-learn",
			minimum_confidence: CONFIDENCES.includes(confidence) ? confidence : "high",
			modified_on: now,
		};
		if (match[2] === undefined) {
			await knex("npmos_waf_host")
				.insert({ proxy_host_id: hostId, ...values })
				.onConflict("proxy_host_id")
				.merge();
		} else {
			const path = parseJson(proxyHost.locations)[Number.parseInt(match[2], 10)]?.path;
			if (!path) {
				continue;
			}
			await knex("npmos_waf_location")
				.insert({ proxy_host_id: hostId, path, ...values })
				.onConflict(["proxy_host_id", "path"])
				.merge();
		}
		imported++;
	}
	return imported;
};

/**
 * At backend start: import from open-appsec-npm on the first start, then generate the policy.
 * Never blocks the start of NPMOS: errors are logged and shown in the GUI.
 */
const bootstrap = async () => {
	try {
		const current = await readPolicyFile();
		if (current !== null && !current.startsWith(HEADER)) {
			await backup(current, "before-npmos");
			const { count } = await db()("npmos_waf_host").count("proxy_host_id as count").first();
			if (Number(count) === 0) {
				const imported = await importLegacy(current);
				if (imported) {
					logger.info(`WAF: imported ${imported} rule(s) from open-appsec-npm`);
				}
			}
		}
		await regenerateNow({ force: true });
	} catch (err) {
		logger.error(`WAF policy bootstrap failed: ${err.message}`);
		debug(logger, err);
	}
};

const getPolicyState = () => ({ file: POLICY_FILE, ...state });

export {
	bootstrap,
	buildPolicy,
	CONFIDENCES,
	getPolicyState,
	MODES,
	readPolicyFile,
	regenerateNow,
	render,
	scheduleRegenerate,
};
