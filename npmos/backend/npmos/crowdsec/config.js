export class ConfigError extends Error {}

/** "4h" → minutes */
export const durationMinutes = (d) => {
	const m = DURATION.exec(d);
	if (!m) throw new ConfigError(`Invalid duration: ${d}`);
	return Number(m[1]) * { m: 1, h: 60, d: 1440 }[m[2]];
};

/** IP or CIDR, normalized; null if invalid */
export const normalizeIpOrCidr = (value) => {
	const text = String(value).trim();
	const [ip, bits, extra] = text.split("/");
	if (extra !== undefined) return null;
	const version = isIP(ip);
	if (!version) return null;
	if (bits === undefined) return ip;
	if (!/^\d{1,3}$/.test(bits) || Number(bits) > (version === 4 ? 32 : 128)) return null;
	return `${ip}/${Number(bits)}`;
};

/** expressions of CrowdSec (expr): one line, no YAML tricks; checked by CrowdSec at start */
const checkExpression = (e, what) => {
	if (typeof e !== "string" || e.length > 1000 || /[\r\n]/.test(e)) {
		throw new ConfigError(`${what}: an expression must be one line of up to 1000 characters`);
	}
};

/**
 * Validates and normalizes settings from the API; keeps the stored captcha secret when the new
 * one is empty (the GUI never gets it back).
 * @param {object} v
 * @returns {object}
 */
export const normalize = (v) => {
	const d = defaults();
	const s = { ...d, ...v };
	const b = { ...d.bouncer, ...s.bouncer, captcha: { ...d.bouncer.captcha, ...s.bouncer?.captcha } };
	if (typeof b.enabled !== "boolean") throw new ConfigError("bouncer.enabled must be a boolean");
	if (!["live", "stream"].includes(b.mode)) throw new ConfigError("Bouncer mode: live or stream");
	if (!DECISION_TYPES.includes(b.fallback)) throw new ConfigError("Fallback remediation: ban or captcha");
	if (!Number.isInteger(b.update_frequency) || b.update_frequency < 1 || b.update_frequency > 3600) {
		throw new ConfigError("Update frequency: 1–3600 s");
	}
	if (!Array.isArray(b.exclude_locations) || b.exclude_locations.length > 50) {
		throw new ConfigError("Excluded locations: up to 50");
	}
	b.exclude_locations = [...new Set(b.exclude_locations.map((l) => String(l).trim()).filter(Boolean))];
	for (const l of b.exclude_locations) {
		if (!LOCATION.test(l) || l.includes(",")) throw new ConfigError(`Invalid location: ${l}`);
	}
	if (!CAPTCHA_PROVIDERS.includes(b.captcha.provider)) throw new ConfigError("Unknown captcha provider");
	for (const k of ["site_key", "secret_key"]) {
		b.captcha[k] = String(b.captcha[k] ?? "").trim();
		if (b.captcha[k].length > 500 || /\s/.test(b.captcha[k])) {
			throw new ConfigError(`Invalid captcha ${k.replace("_", " ")}`);
		}
	}
	if (b.captcha.provider && !b.captcha.site_key) throw new ConfigError("The captcha needs a site key");

	const sources = { ...d.sources, ...s.sources };
	if (![sources.nginx, sources.openappsec].every((x) => typeof x === "boolean")) {
		throw new ConfigError("Sources must be booleans");
	}

	const appsec = { ...d.appsec, ...s.appsec };
	if (typeof appsec.enabled !== "boolean") throw new ConfigError("appsec.enabled must be a boolean");
	if (!["passthrough", "deny"].includes(appsec.failure_action)) {
		throw new ConfigError("AppSec failure action: passthrough or deny");
	}
	if (!Array.isArray(appsec.configs) || appsec.configs.length > 20) throw new ConfigError("AppSec configs: up to 20");
	appsec.configs = [...new Set(appsec.configs)];
	if (appsec.enabled && !appsec.configs.length) throw new ConfigError("AppSec needs at least one configuration");
	for (const c of appsec.configs) {
		if (typeof c !== "string" || !HUB_NAME.test(c)) throw new ConfigError(`Invalid AppSec configuration: ${c}`);
	}

	if (!Array.isArray(s.profiles) || s.profiles.length > 30) throw new ConfigError("Profiles: up to 30");
	const names = new Set();
	const profiles = s.profiles.map((p) => {
		const profile = { ...d.profiles[0], ...p };
		if (!NAME.test(profile.name) || names.has(profile.name)) {
			throw new ConfigError(`Profile name: unique, a-z 0-9 _ - (${profile.name})`);
		}
		names.add(profile.name);
		if (typeof profile.enabled !== "boolean" || typeof profile.escalate !== "boolean") {
			throw new ConfigError("Profile flags must be booleans");
		}
		if (!SCOPES.includes(profile.scope)) throw new ConfigError(`Profile scope: ${SCOPES.join(", ")}`);
		if (!DECISION_TYPES.includes(profile.type)) throw new ConfigError("Profile decision: ban or captcha");
		durationMinutes(profile.duration);
		if (!Array.isArray(profile.scenarios) || profile.scenarios.length > 50) {
			throw new ConfigError("Profile scenarios: up to 50");
		}
		for (const sc of profile.scenarios) {
			if (typeof sc !== "string" || !HUB_NAME.test(sc)) throw new ConfigError(`Invalid scenario: ${sc}`);
		}
		profile.filter = String(profile.filter ?? "").trim();
		checkExpression(profile.filter, `Profile ${profile.name}`);
		return {
			name: profile.name,
			enabled: profile.enabled,
			scope: profile.scope,
			scenarios: profile.scenarios,
			filter: profile.filter,
			type: profile.type,
			duration: profile.duration,
			escalate: profile.escalate,
		};
	});

	const allow = { ...d.allowlist, ...s.allowlist };
	if (!Array.isArray(allow.ips) || allow.ips.length > 1000) throw new ConfigError("Allowlist: up to 1000 addresses");
	const ips = [];
	for (const ip of allow.ips) {
		const n = normalizeIpOrCidr(ip);
		if (!n) throw new ConfigError(`Allowlist: invalid IP or CIDR: ${ip}`);
		if (!ips.includes(n)) ips.push(n);
	}
	if (!Array.isArray(allow.expressions) || allow.expressions.length > 50) {
		throw new ConfigError("Allowlist: up to 50 expressions");
	}
	const expressions = allow.expressions.map((e) => String(e).trim()).filter(Boolean);
	for (const e of expressions) checkExpression(e, "Allowlist");
	if (typeof allow.private !== "boolean") throw new ConfigError("allowlist.private must be a boolean");

	const ban = { ...d.openappsec_ban, ...s.openappsec_ban };
	if (typeof ban.enabled !== "boolean") throw new ConfigError("openappsec_ban.enabled must be a boolean");
	if (!Number.isInteger(ban.events) || ban.events < 1 || ban.events > 1000) {
		throw new ConfigError("Blocked requests before a ban: 1–1000");
	}
	if (!Number.isInteger(ban.minutes) || ban.minutes < 1 || ban.minutes > 1440) {
		throw new ConfigError("Window: 1–1440 minutes");
	}

	if (!LOG_LEVELS.includes(s.log_level)) throw new ConfigError("Unknown log level");
	if (typeof s.online_hub !== "boolean") throw new ConfigError("online_hub must be a boolean");

	return {
		bouncer: b,
		sources,
		appsec,
		profiles,
		allowlist: { ips, expressions, private: allow.private },
		openappsec_ban: ban,
		log_level: s.log_level,
		online_hub: s.online_hub,
	};
};

const docs = (items) => HEADER + items.map((i) => YAML.stringify(i, { lineWidth: 0 })).join("---\n");

/** acquis.d/npmos.yaml */
export const renderAcquis = (s) => {
	const items = [];
	if (s.sources.nginx) {
		items.push({ source: "file", filenames: NGINX_LOGS, labels: { type: "npmplus" } });
	}
	if (s.sources.openappsec) {
		items.push({
			source: "file",
			filenames: [OPENAPPSEC_LOGS],
			exclude_regexps: ["\\.gz$"],
			labels: { type: "openappsec" },
		});
	}
	if (s.appsec.enabled) {
		items.push({
			source: "appsec",
			name: "npmos-appsec",
			listen_addr: APPSEC_LISTEN,
			appsec_configs: s.appsec.configs,
			labels: { type: "appsec" },
		});
	}
	return items.length ? docs(items) : null;
};

const scopeFilter = (scope) => {
	if (scope === "any") return "Alert.Remediation == true";
	return `Alert.Remediation == true && Alert.GetScope() == "${scope}"`;
};

/** profiles.yaml: the first profile that matches an alert decides (on_success: break) */
export const renderProfiles = (s) => {
	const items = s.profiles
		.filter((p) => p.enabled)
		.map((p) => {
			let filter = scopeFilter(p.scope);
			if (p.scenarios.length) filter += ` && Alert.GetScenario() in ${JSON.stringify(p.scenarios)}`;
			if (p.filter) filter += ` && (${p.filter})`;
			const profile = {
				name: `npmos_${p.name}`,
				filters: [filter],
				decisions: [{ type: p.type, duration: p.duration }],
			};
			// every next decision for the same value lasts one base duration longer
			if (p.escalate) {
				profile.duration_expr = `Sprintf('%dm', (GetDecisionsCount(Alert.GetValue()) + 1) * ${durationMinutes(p.duration)})`;
			}
			profile.on_success = "break";
			return profile;
		});
	// CrowdSec does not start without a profile; this one never matches
	if (!items.length) {
		items.push({ name: "npmos_none", filters: ["false"], decisions: [{ type: "ban", duration: "1m" }] });
	}
	return docs(items);
};

/** parsers/s02-enrich/npmos-allowlist.yaml */
export const renderAllowlist = (s) => {
	const { ips, expressions } = s.allowlist;
	if (!ips.length && !expressions.length) return null;
	const whitelist = { reason: "NPMOS allowlist" };
	const single = ips.filter((ip) => !ip.includes("/"));
	const cidr = ips.filter((ip) => ip.includes("/"));
	if (single.length) whitelist.ip = single;
	if (cidr.length) whitelist.cidr = cidr;
	if (expressions.length) whitelist.expression = expressions;
	return docs([{ name: "npmos/allowlist", description: "Allowlist of NPMOS", whitelist }]);
};

/** scenarios/npmos-openappsec-prevent.yaml: N requests of an IP blocked by open-appsec in M minutes */
export const renderScenario = (s) => {
	const { enabled, events, minutes } = s.openappsec_ban;
	if (!enabled || !s.sources.openappsec) return null;
	const scenario = {
		type: events === 1 ? "trigger" : "leaky",
		name: SCENARIO_NAME,
		description: `NPMOS: ${events} request(s) of one IP blocked by open-appsec in ${minutes} min`,
		filter: "evt.Meta.log_type == 'openappsec_security_log' && Lower(evt.Meta.security_action) == 'prevent'",
		groupby: "evt.Meta.source_ip",
	};
	if (events > 1) {
		scenario.capacity = events - 1;
		scenario.leakspeed = `${Math.max(1, Math.round((minutes * 60) / events))}s`;
	}
	scenario.blackhole = "1m";
	scenario.labels = {
		service: "http",
		behavior: "http:exploit",
		label: "open-appsec blocked requests",
		classification: ["attack.T1190"],
		confidence: 3,
		spoofable: 0,
		remediation: true,
	};
	return docs([scenario]);
};

