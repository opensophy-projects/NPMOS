/**
 * /data/crowdsec/crowdsec.conf of the Lua bouncer of NPMplus (KEY=value lines)
 * @param {object} s
 * @param {{apiKey: string, captchaSecret: string}} secrets
 */
export const renderBouncer = (s, { apiKey, captchaSecret }) => {
	const b = s.bouncer;
	const lines = {
		ENABLED: b.enabled,
		API_URL: LAPI_URL,
		API_KEY: apiKey,
		USE_TLS_AUTH: false,
		CACHE_EXPIRATION: 1,
		BOUNCING_ON_TYPE: "all",
		FALLBACK_REMEDIATION: b.fallback,
		REQUEST_TIMEOUT: 3000,
		UPDATE_FREQUENCY: b.update_frequency,
		ENABLE_INTERNAL: false,
		MODE: b.mode,
		EXCLUDE_LOCATION: b.exclude_locations.join(","),
		BAN_TEMPLATE_PATH: "/data/crowdsec/ban.html",
		REDIRECT_LOCATION: "",
		RET_CODE: "",
		CAPTCHA_PROVIDER: b.captcha.provider,
		SECRET_KEY: b.captcha.provider ? captchaSecret : "",
		SITE_KEY: b.captcha.provider ? b.captcha.site_key : "",
		CAPTCHA_TEMPLATE_PATH: "/data/crowdsec/captcha.html",
		CAPTCHA_EXPIRATION: 3600,
		APPSEC_URL: s.appsec.enabled ? APPSEC_URL : "",
		APPSEC_FAILURE_ACTION: s.appsec.failure_action,
		APPSEC_CONNECT_TIMEOUT: "",
		APPSEC_SEND_TIMEOUT: 1000,
		APPSEC_PROCESS_TIMEOUT: 30000,
		ALWAYS_SEND_TO_APPSEC: false,
		APPSEC_DROP_UNREADABLE_BODY: false,
		SSL_VERIFY: true,
	};
	return `${HEADER}${Object.entries(lines)
		.map(([k, v]) => `${k}=${v}`)
		.join("\n")}\n`;
};

/** hub items the generated files rely on */
export const requiredItems = (s) => {
	const items = [];
	if (s.sources.nginx) items.push(["collections", NGINX_COLLECTION]);
	if (s.sources.openappsec && s.openappsec_ban.enabled) items.push(["parsers", OPENAPPSEC_PARSER]);
	if (s.appsec.enabled) for (const c of s.appsec.configs) items.push(["appsec-configs", c]);
	if (s.allowlist.private) items.push(["parsers", PRIVATE_ALLOWLIST]);
	return items;
};

/** hub items the settings switch off */
export const unwantedItems = (s) => (s.allowlist.private ? [] : [["parsers", PRIVATE_ALLOWLIST]]);

const HOOK = "cs.Allow(ngx.var.remote_addr)";

/** conf.d/crowdsec.conf from the one of NPMplus; perHost: false if its Lua code changed */
export const renderNginx = (template) => {
	if (!template.includes(HOOK)) return { text: template, perHost: false };
	const text = template.replace(HOOK, `if ngx.var.npmos_crowdsec_off ~= "1" then\n\t\t\t${HOOK}\n\t\tend`);
	return { text: `${HEADER}map $host $npmos_crowdsec_off {\n\tdefault 0;\n}\n\n${text}`, perHost: true };
};

/** messages of the fatal errors CrowdSec logged at its last start */
export const fatalMessages = (lines) => {
	const out = [];
	for (const l of lines) {
		const text = String(l.line ?? l);
		if (!/level=(fatal|error)/.test(text)) continue;
		const m = /msg="((?:[^"\\]|\\.)*)"/.exec(text);
		const msg = (m ? m[1].replace(/\\n/g, " ").replace(/\\(.)/g, "$1") : text).replace(/\s+/g, " ").trim();
		if (!out.includes(msg)) out.push(msg);
	}
	return out.slice(-3);
};
