#!/usr/bin/env node
// NPMOS control plane (npmos-control): the only way the NPMOS backend reaches the Docker API.
//
// Runs from the npmos image as its own container (deploy/compose.yaml) on two internal networks:
// "internal" (the backend calls it) and "control" (it calls socket-proxy). The backend is
// internet-facing, so it never gets Docker access itself; this service narrows what socket-proxy
// allows down to a whitelist:
//   - only containers of this compose project labelled npmos.managed=true;
//   - only these operations: list (state, health, version), restart, read logs.
// Every request needs the shared token generated by npmos-init and is written to stdout as a JSON
// audit line (who, what, result). The backend also records user actions in the NPMOS audit log.
//
// No dependencies besides Node.js, so it runs from the backend directory of the npmos image as is.
import { readFileSync } from "node:fs";
import http from "node:http";
import { hostname } from "node:os";
import { timingSafeEqual } from "node:crypto";

const PORT = Number.parseInt(process.env.NPMOS_CONTROL_PORT || "7080", 10);
const DOCKER_HOST = process.env.NPMOS_DOCKER_HOST || "http://socket-proxy:2375";
const TOKEN_FILE = process.env.NPMOS_CONTROL_TOKEN_FILE || "/run/secrets/control_token";
const DOCKER_TIMEOUT_MS = 15000;
const MAX_LOG_LINES = 5000;
const MANAGED_LABEL = "npmos.managed";
const PROJECT_LABEL = "com.docker.compose.project";
const SERVICE_LABEL = "com.docker.compose.service";
const NOT_RESTARTABLE = ["npmos-control", "socket-proxy"];

const token = Buffer.from(readFileSync(TOKEN_FILE, "utf8").trim());
if (token.length < 32) {
	throw new Error(`${TOKEN_FILE}: token too short`);
}

const audit = (entry) => {
	process.stdout.write(`${JSON.stringify({ time: new Date().toISOString(), ...entry })}\n`);
};

class HttpError extends Error {
	constructor(status, message) {
		super(message);
		this.status = status;
	}
}

/**
 * @param   {string} method
 * @param   {string} path    Docker API path with query
 * @returns {Promise<Response>}
 */
const docker = async (method, path) => {
	let response;
	try {
		response = await fetch(`${DOCKER_HOST}${path}`, { method, signal: AbortSignal.timeout(DOCKER_TIMEOUT_MS) });
	} catch (err) {
		throw new HttpError(502, `Docker API unreachable: ${err.cause?.code || err.message}`);
	}
	if (!response.ok) {
		const text = await response.text();
		throw new HttpError(502, `Docker API ${method} ${path.split("?")[0]}: ${response.status} ${text.trim()}`);
	}
	return response;
};

// The compose project is taken from this container's own labels, so several NPMOS stacks on one
// host never see each other's containers.
let project = null;
const getProject = async () => {
	if (!project) {
		const self = await (await docker("GET", `/containers/${encodeURIComponent(hostname())}/json`)).json();
		project = self.Config?.Labels?.[PROJECT_LABEL];
		if (!project) {
			throw new HttpError(500, "npmos-control is not running as part of a compose project");
		}
	}
	return project;
};

const listManaged = async () => {
	const filters = JSON.stringify({ label: [`${PROJECT_LABEL}=${await getProject()}`, `${MANAGED_LABEL}=true`] });
	const containers = await (
		await docker("GET", `/containers/json?all=true&filters=${encodeURIComponent(filters)}`)
	).json();
	return containers.map((c) => ({
		id: c.Id,
		service: c.Labels[SERVICE_LABEL],
		name: (c.Names?.[0] || "").replace(/^\//, ""),
		image: c.Image,
		version: c.Labels["org.opencontainers.image.version"] || c.Image.split(":").pop() || null,
		state: c.State,
		status: c.Status,
		created: c.Created,
		restartable: !NOT_RESTARTABLE.includes(c.Labels[SERVICE_LABEL]),
		networkMode: c.HostConfig?.NetworkMode || null,
	}));
};

const findService = async (service) => {
	const container = (await listManaged()).find((c) => c.service === service);
	if (!container) {
		throw new HttpError(404, `Unknown service: ${service}`);
	}
	return container;
};

const inspect = async (service) => {
	const container = await findService(service);
	const details = await (await docker("GET", `/containers/${container.id}/json`)).json();
	return {
		...container,
		startedAt: details.State?.StartedAt || null,
		finishedAt: details.State?.FinishedAt || null,
		restartCount: details.RestartCount ?? 0,
		exitCode: details.State?.ExitCode ?? null,
		health: details.State?.Health?.Status || null,
		error: details.State?.Error || null,
	};
};

// Without a TTY the logs endpoint multiplexes stdout/stderr: 8-byte header (stream, 0,0,0, size BE32)
const demux = (buf) => {
	const lines = [];
	let offset = 0;
	while (offset + 8 <= buf.length) {
		const stream = buf[offset] === 2 ? "stderr" : "stdout";
		const size = buf.readUInt32BE(offset + 4);
		const chunk = buf.subarray(offset + 8, offset + 8 + size).toString("utf8");
		for (const line of chunk.split("\n")) {
			if (line !== "") {
				lines.push({ stream, line });
			}
		}
		offset += 8 + size;
	}
	return lines;
};

const logs = async (service, tail, since) => {
	const container = await findService(service);
	const params = new URLSearchParams({ stdout: "1", stderr: "1", timestamps: "1", tail: String(tail) });
	if (since) {
		params.set("since", String(since));
	}
	const response = await docker("GET", `/containers/${container.id}/logs?${params}`);
	return demux(Buffer.from(await response.arrayBuffer()));
};

const restart = async (service) => {
	const container = await findService(service);
	// the control path itself: a restart would cut the request asking for it, with no way to report back
	if (NOT_RESTARTABLE.includes(container.service)) {
		throw new HttpError(400, `${service} cannot be restarted from NPMOS`);
	}
	return container;
};

const authorized = (req) => {
	const header = req.headers.authorization || "";
	const given = Buffer.from(header.startsWith("Bearer ") ? header.slice(7) : "");
	return given.length === token.length && timingSafeEqual(given, token);
};

const send = (res, status, body) => {
	res.writeHead(status, { "Content-Type": "application/json" });
	res.end(JSON.stringify(body));
};

const intParam = (value, fallback, max) => {
	const n = Number.parseInt(value ?? "", 10);
	return Number.isFinite(n) && n > 0 ? Math.min(n, max) : fallback;
};

const server = http.createServer(async (req, res) => {
	const url = new URL(req.url, "http://npmos-control");
	const actor = `${req.headers["x-npmos-actor"] || ""}`.slice(0, 200) || null;
	const entry = { actor, method: req.method, path: url.pathname };

	if (url.pathname === "/healthz") {
		return send(res, 200, { status: "OK" });
	}
	if (!authorized(req)) {
		audit({ ...entry, result: "denied" });
		return send(res, 401, { error: "Unauthorized" });
	}

	try {
		const parts = url.pathname.split("/").filter(Boolean);
		let result;
		let after = null;

		if (req.method === "GET" && url.pathname === "/v1/services") {
			result = await listManaged();
		} else if (parts[0] === "v1" && parts[1] === "services" && parts.length >= 3) {
			const service = decodeURIComponent(parts[2]);
			const action = parts[3];
			if (req.method === "GET" && !action) {
				result = await inspect(service);
			} else if (req.method === "GET" && action === "logs") {
				const since = intParam(url.searchParams.get("since"), 0, Number.MAX_SAFE_INTEGER);
				result = await logs(service, intParam(url.searchParams.get("tail"), 200, MAX_LOG_LINES), since);
			} else if (req.method === "POST" && action === "restart") {
				const container = await restart(service);
				const doRestart = async () => {
					await docker("POST", `/containers/${container.id}/restart?t=10`);
					// containers in this one's network (and IPC) namespace, e.g. the open-appsec agent in
					// npmos's, keep the old namespace after a restart and lose the network: restart them too
					const dependents = (await listManaged()).filter(
						(c) => c.networkMode === `container:${container.id}`,
					);
					for (const dependent of dependents) {
						await docker("POST", `/containers/${dependent.id}/restart?t=10`);
						audit({ ...entry, result: "restarted dependent", dependent: dependent.service });
					}
				};
				if (container.service === "npmos") {
					// answer first: restarting npmos cuts the backend's own request
					after = doRestart;
					result = { service, restarted: false, restarting: true };
				} else {
					await doRestart();
					result = { service, restarted: true };
				}
			}
		}

		if (result === undefined) {
			throw new HttpError(404, "Unknown operation");
		}
		// reads are frequent (status page polling); only changes go to the audit log
		if (req.method !== "GET") {
			audit({ ...entry, result: "ok" });
		}
		send(res, req.method === "POST" ? 202 : 200, result);
		if (after) {
			after().then(
				() => audit({ ...entry, result: "restarted" }),
				(err) => audit({ ...entry, result: "failed", error: err.message }),
			);
		}
	} catch (err) {
		const status = err instanceof HttpError ? err.status : 500;
		audit({ ...entry, result: "error", status, error: err.message });
		send(res, status, { error: err.message });
	}
});

server.listen(PORT, () => {
	audit({ event: "listening", port: PORT, docker: DOCKER_HOST });
});

for (const signal of ["SIGINT", "SIGTERM"]) {
	process.on(signal, () => server.close(() => process.exit(0)));
}
