#!/usr/bin/env node
// NPMOS control plane (npmos-control): the only way the NPMOS backend reaches the Docker API.
//
// Runs in the openappsec container (deploy/openappsec/npmos-openappsec.sh), which has the Docker socket; the
// npmos container, internet-facing, never gets Docker access itself. It listens on 127.0.0.1 of the network
// namespace npmos shares with openappsec, and allows only a whitelist:
//   - only containers of this compose project labelled npmos.managed=true;
//   - only these operations: list (state, health, version), restart, read logs, and a reload
//     (SIGHUP) of the services that reread their configuration on it (RELOADABLE).
// Every request needs the shared token generated by npmos-init and is written to stdout as a JSON
// audit line (who, what, result). The backend also records user actions in the NPMOS audit log.
//
// No dependencies besides Node.js (the image copies this directory as is).
import { readFileSync } from "node:fs";
import http from "node:http";
import { hostname } from "node:os";
import { timingSafeEqual } from "node:crypto";
import { repairNamespaces } from "./watchdog.js";

const PORT = Number.parseInt(process.env.NPMOS_CONTROL_PORT || "7080", 10);
// 127.0.0.1: the namespace is that of nginx, which other containers of the networks also reach
const LISTEN = process.env.NPMOS_CONTROL_LISTEN || "127.0.0.1";
const DOCKER_SOCKET = process.env.NPMOS_DOCKER_SOCKET || "/var/run/docker.sock";
// the service of this container: its "restart" restarts the agent process, not the container (with this service)
const OWN_SERVICE = process.env.NPMOS_CONTROL_SERVICE || "openappsec";
const AGENT_PID_FILE = process.env.NPMOS_AGENT_PID_FILE || "/run/npmos-agent.pid";
const TOKEN_FILE = process.env.NPMOS_CONTROL_TOKEN_FILE || "/run/secrets/control_token";
const DOCKER_TIMEOUT_MS = 15000;
const MAX_LOG_LINES = 5000;
// npmos is restarted this long after npmos-control has answered (see the restart route)
const RESTART_GRACE_MS = 2000;
const MANAGED_LABEL = "npmos.managed";
const PROJECT_LABEL = "com.docker.compose.project";
const SERVICE_LABEL = "com.docker.compose.service";
// CrowdSec rereads acquisition, parsers, scenarios and profiles on SIGHUP: seconds instead of a restart
const RELOADABLE = ["crowdsec"];

const token = Buffer.from(readFileSync(TOKEN_FILE, "utf8").trim());
if (token.length < 32) {
	throw new Error(`${TOKEN_FILE}: token too short`);
}

const audit = (entry) => {
	process.stdout.write(`${JSON.stringify({ time: new Date().toISOString(), ...entry })}\n`);
};

class HttpError extends Error {
	constructor(status, message) {
		super(message);
		this.status = status;
	}
}

/**
 * The Docker API over its socket. Answers like fetch: {ok, status, json(), text(), arrayBuffer()}.
 * @param   {string} method
 * @param   {string} path    Docker API path with query
 */
const docker = (method, path) =>
	new Promise((resolve, reject) => {
		const req = http.request(
			{ socketPath: DOCKER_SOCKET, method, path, headers: { Host: "docker" }, timeout: DOCKER_TIMEOUT_MS },
			(res) => {
				const chunks = [];
				res.on("data", (c) => chunks.push(c));
				res.on("end", () => {
					const body = Buffer.concat(chunks);
					const status = res.statusCode ?? 0;
					const response = {
						ok: status >= 200 && status < 300,
						status,
						text: async () => body.toString("utf8"),
						json: async () => JSON.parse(body.toString("utf8") || "null"),
						arrayBuffer: async () => body,
					};
					if (!response.ok) {
						reject(
							new HttpError(
								502,
								`Docker API ${method} ${path.split("?")[0]}: ${status} ${body.toString("utf8").trim()}`,
							),
						);
						return;
					}
					resolve(response);
				});
			},
		);
		req.on("timeout", () => req.destroy(new Error("timeout")));
		req.on("error", (err) => reject(new HttpError(502, `Docker API unreachable: ${err.code || err.message}`)));
		req.end();
	});

// The compose project is taken from this container's own labels, so several NPMOS stacks on one
// host never see each other's containers.
let project = null;
const getProject = async () => {
	if (!project) {
		const self = await (await docker("GET", `/containers/${encodeURIComponent(hostname())}/json`)).json();
		project = self.Config?.Labels?.[PROJECT_LABEL];
		if (!project) {
			throw new HttpError(500, "npmos-control is not running as part of a compose project");
		}
	}
	return project;
};

const addressesOf = (c) =>
	Object.entries(c.NetworkSettings?.Networks ?? {})
		.filter(([, n]) => n.IPAddress)
		.map(([network, n]) => ({ network, ip: n.IPAddress }));

/** the ports a container listens on, once per port and protocol (published ones with the port of the host) */
const portsOf = (c) =>
	[
		...new Map(
			(c.Ports ?? []).map((p) => [
				`${p.PrivatePort}/${p.Type}`,
				{ port: p.PrivatePort, type: p.Type, published: p.PublicPort ?? null },
			]),
		).values(),
	].sort((x, y) => x.port - y.port || (x.type < y.type ? -1 : x.type > y.type ? 1 : 0));

const listManaged = async () => {
	const filters = JSON.stringify({ label: [`${PROJECT_LABEL}=${await getProject()}`, `${MANAGED_LABEL}=true`] });
	const containers = await (
		await docker("GET", `/containers/json?all=true&filters=${encodeURIComponent(filters)}`)
	).json();
	return containers.map((c) => ({
		id: c.Id,
		service: c.Labels[SERVICE_LABEL],
		name: (c.Names?.[0] || "").replace(/^\//, ""),
		image: c.Image,
		version: c.Labels["org.opencontainers.image.version"] || c.Image.split(":").pop() || null,
		state: c.State,
		status: c.Status,
		created: c.Created,
		restartable: true,
		networkMode: c.HostConfig?.NetworkMode || null,
		// addresses in its networks and the ports it listens on (published ones with the address of the host)
		addresses: addressesOf(c),
		ports: portsOf(c),
	}));
};

/**
 * Applications: running containers outside this stack in a network of npmos, which nginx reaches by name. Read
 * only (name, image, addresses, ports): System -> Services offers to publish them as a proxy host.
 */
const listApps = async () => {
	const project = await getProject();
	const containers = await (await docker("GET", "/containers/json")).json();
	// nginx runs in the network namespace of openappsec: its networks are those of npmos
	const own = containers.find(
		(c) => c.Labels?.[PROJECT_LABEL] === project && c.Labels?.[SERVICE_LABEL] === OWN_SERVICE,
	);
	const networks = Object.keys(own?.NetworkSettings?.Networks ?? {});
	return containers
		.filter((c) => c.Labels?.[PROJECT_LABEL] !== project)
		.filter((c) => Object.keys(c.NetworkSettings?.Networks ?? {}).some((n) => networks.includes(n)))
		.map((c) => ({
			name: (c.Names?.[0] || "").replace(/^\//, ""),
			image: c.Image,
			status: c.Status,
			addresses: addressesOf(c).filter((a) => networks.includes(a.network)),
			ports: portsOf(c),
		}));
};

const findService = async (service) => {
	const container = (await listManaged()).find((c) => c.service === service);
	if (!container) {
		throw new HttpError(404, `Unknown service: ${service}`);
	}
	return container;
};

const inspect = async (service) => {
	const container = await findService(service);
	const details = await (await docker("GET", `/containers/${container.id}/json`)).json();
	return {
		...container,
		startedAt: details.State?.StartedAt || null,
		finishedAt: details.State?.FinishedAt || null,
		restartCount: details.RestartCount ?? 0,
		exitCode: details.State?.ExitCode ?? null,
		health: details.State?.Health?.Status || null,
		error: details.State?.Error || null,
	};
};

// Without a TTY the logs endpoint multiplexes stdout/stderr: 8-byte header (stream, 0,0,0, size BE32)
const demux = (buf) => {
	const lines = [];
	let offset = 0;
	while (offset + 8 <= buf.length) {
		const stream = buf[offset] === 2 ? "stderr" : "stdout";
		const size = buf.readUInt32BE(offset + 4);
		const chunk = buf.subarray(offset + 8, offset + 8 + size).toString("utf8");
		for (const line of chunk.split("\n")) {
			if (line !== "") {
				lines.push({ stream, line });
			}
		}
		offset += 8 + size;
	}
	return lines;
};

const logs = async (service, tail, since) => {
	const container = await findService(service);
	const params = new URLSearchParams({ stdout: "1", stderr: "1", timestamps: "1", tail: String(tail) });
	if (since) {
		params.set("since", String(since));
	}
	const response = await docker("GET", `/containers/${container.id}/logs?${params}`);
	return demux(Buffer.from(await response.arrayBuffer()));
};

const agentPid = () => {
	try {
		return Number.parseInt(readFileSync(AGENT_PID_FILE, "utf8").trim(), 10);
	} catch {
		return Number.NaN;
	}
};

/**
 * The agent process of this container: TERM, npmos-openappsec.sh starts it again with the settings of the GUI.
 * @returns {number} the pid of the old process
 */
const restartAgentProcess = () => {
	const pid = agentPid();
	if (!Number.isInteger(pid) || pid < 2) throw new HttpError(500, `No agent process in ${AGENT_PID_FILE}`);
	process.kill(pid, "SIGTERM");
	return pid;
};

/** the new agent is up: another pid than the old one, and its local API answers (the backend asks it there) */
const agentUp = async (oldPid, timeoutMs = 120000) => {
	const until = Date.now() + timeoutMs;
	while (Date.now() < until) {
		await new Promise((resolve) => setTimeout(resolve, 2000));
		if (agentPid() === oldPid) continue;
		const ok = await new Promise((resolve) => {
			const req = http.get({ host: "127.0.0.1", port: 7777, path: "/", timeout: 2000 }, (res) => {
				res.resume();
				resolve(true);
			});
			req.on("timeout", () => req.destroy());
			req.on("error", () => resolve(false));
		});
		if (ok) return true;
	}
	return false;
};

const authorized = (req) => {
	const header = req.headers.authorization || "";
	const given = Buffer.from(header.startsWith("Bearer ") ? header.slice(7) : "");
	return given.length === token.length && timingSafeEqual(given, token);
};

const send = (res, status, body) => {
	res.writeHead(status, { "Content-Type": "application/json" });
	res.end(JSON.stringify(body));
};

const intParam = (value, fallback, max) => {
	const n = Number.parseInt(value ?? "", 10);
	return Number.isFinite(n) && n > 0 ? Math.min(n, max) : fallback;
};

const server = http.createServer(async (req, res) => {
	const url = new URL(req.url, "http://npmos-control");
	const actor = `${req.headers["x-npmos-actor"] || ""}`.slice(0, 200) || null;
	const entry = { actor, method: req.method, path: url.pathname };

	if (url.pathname === "/healthz") {
		return send(res, 200, { status: "OK" });
	}
	if (!authorized(req)) {
		audit({ ...entry, result: "denied" });
		return send(res, 401, { error: "Unauthorized" });
	}

	try {
		const parts = url.pathname.split("/").filter(Boolean);
		let result;
		let after = null;

		if (req.method === "GET" && url.pathname === "/v1/services") {
			result = await listManaged();
		} else if (req.method === "GET" && url.pathname === "/v1/apps") {
			result = await listApps();
		} else if (parts[0] === "v1" && parts[1] === "services" && parts.length >= 3) {
			const service = decodeURIComponent(parts[2]);
			const action = parts[3];
			if (req.method === "GET" && !action) {
				result = await inspect(service);
			} else if (req.method === "GET" && action === "logs") {
				const since = intParam(url.searchParams.get("since"), 0, Number.MAX_SAFE_INTEGER);
				result = await logs(service, intParam(url.searchParams.get("tail"), 200, MAX_LOG_LINES), since);
			} else if (req.method === "POST" && action === "reload") {
				const container = await findService(service);
				if (!RELOADABLE.includes(container.service)) {
					throw new HttpError(400, `${service} cannot be reloaded`);
				}
				await docker("POST", `/containers/${container.id}/kill?signal=SIGHUP`);
				result = { service, reloaded: true };
			} else if (req.method === "POST" && action === "restart") {
				const container = await findService(service);
				const dependentsOf = async (id) =>
					(await listManaged()).filter((c) => c.networkMode === `container:${id}`);
				if (container.service === OWN_SERVICE) {
					// this container: the agent process is restarted (a restart of the container would end this
					// service in the middle of it); then npmos, so that the nginx attachment attaches to the new agent
					after = async () => {
						const oldPid = restartAgentProcess();
						if (!(await agentUp(oldPid))) audit({ ...entry, result: "agent slow to start" });
						for (const dependent of await dependentsOf(container.id)) {
							await docker("POST", `/containers/${dependent.id}/restart?t=10`);
							audit({ ...entry, result: "restarted dependent", dependent: dependent.service });
						}
					};
					result = { service, restarted: false, restarting: true };
				} else {
					const doRestart = async () => {
						await docker("POST", `/containers/${container.id}/restart?t=10`);
						// containers in this one's network (and IPC) namespace keep the old namespace after a
						// restart and lose the network: restart them too
						for (const dependent of await dependentsOf(container.id)) {
							await docker("POST", `/containers/${dependent.id}/restart?t=10`);
							audit({ ...entry, result: "restarted dependent", dependent: dependent.service });
						}
					};
					if (container.service === "npmos") {
						// answer first: restarting npmos cuts the backend's own request
						after = doRestart;
						result = { service, restarted: false, restarting: true };
					} else {
						await doRestart();
						result = { service, restarted: true };
					}
				}
			}
		}

		if (result === undefined) {
			throw new HttpError(404, "Unknown operation");
		}
		// reads are frequent (status page polling); only changes go to the audit log
		if (req.method !== "GET") {
			audit({ ...entry, result: "ok" });
		}
		send(res, req.method === "POST" ? 202 : 200, result);
		if (after) {
			// the backend still has to pass this answer on to its own client through nginx: a restart right
			// away can cut that answer (curl: unexpected eof), so give it a moment
			await new Promise((resolve) => setTimeout(resolve, RESTART_GRACE_MS));
			after().then(
				() => audit({ ...entry, result: "restarted" }),
				(err) => audit({ ...entry, result: "failed", error: err.message }),
			);
		}
	} catch (err) {
		const status = err instanceof HttpError ? err.status : 500;
		audit({ ...entry, result: "error", status, error: err.message });
		send(res, status, { error: err.message });
	}
});

server.listen(PORT, LISTEN, () => {
	audit({ event: "listening", address: `${LISTEN}:${PORT}`, docker: DOCKER_SOCKET });
});

const inspectContainer = async (id) => (await docker("GET", `/containers/${id}/json`)).json();
const restartContainer = (id) => docker("POST", `/containers/${id}/restart?t=10`);

const WATCHDOG_MS = 30 * 1000;
const repairAll = () => repairNamespaces(listManaged, inspectContainer, restartContainer);
if (process.env.NPMOS_CONTROL_WATCHDOG !== "false") {
	const tick = () =>
		repairAll().then(
			(repaired) => {
				for (const service of repaired)
					audit({ actor: "watchdog", result: "restarted", service, reason: "network namespace" });
			},
			// the Docker API may not answer yet at boot: the next tick tries again
			() => undefined,
		);
	setTimeout(tick, 5000).unref();
	setInterval(tick, WATCHDOG_MS).unref();
}

for (const signal of ["SIGINT", "SIGTERM"]) {
	process.on(signal, () => server.close(() => process.exit(0)));
}
