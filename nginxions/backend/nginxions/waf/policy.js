// open-appsec declarative policy (local_policy.yaml).
//
// The source of truth is the database: objects of the policy (nginxions_waf_object, the default policy),
// WAF settings of proxy hosts and locations (nginxions_waf_host / nginxions_waf_location). The file is
// generated on every change and is never edited by hand; it is v1beta2, which the agent of NginxionS applies
// completely (docs/WAF-POLICY.md, objects/format.js). Rules keep the names of open-appsec-npm
// (npm-managed-specific-rule-proxyhost-<id>), so an installation of open-appsec-npm is imported as is.
//
// The agent sees the file through the shared volume (/ext/appsec in both containers, symlinked by
// the agent to /etc/cp/conf/local_policy.yaml). After a write NginxionS asks the agent to apply it
// (set-apply-policy on its local REST port, the agent shares the network namespace of nginxions);
// autoPolicyLoad in the agent picks the change up within 30 s anyway.
import { mkdir, readdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import _ from "lodash";
import YAML from "yaml";
import db from "../../db.js";
import { debug, global as logger } from "../../logger.js";
import { getCurrentCustom, mergeCustom, parseCustom } from "./custom.js";
import { appsecRules, forAgent, schemaFiles, setEngines } from "./engines.js";
import { applyFiles } from "./files.js";
import { asV2, danglingRefs, extraRefs } from "./objects/format.js";
import { UNSUPPORTED_ENGINES } from "./objects/model.js";
import { buildDoc, seedBuiltins } from "./objects/store.js";
import { listSchemas } from "./schemas.js";

const POLICY_FILE = process.env.NGINXIONS_APPSEC_POLICY_FILE || "/ext/appsec/local_policy.yaml";
const BACKUP_DIR = "/data/nginxions/waf/policy-backups";
const BACKUPS_KEPT = 20;
const AGENT_URL = process.env.NGINXIONS_APPSEC_ORCHESTRATION_URL || "http://127.0.0.1:7777";
const AGENT_POLICY_PATH = "/etc/cp/conf/local_policy.yaml";
const APPLY_TIMEOUT_MS = 3000;
const DEBOUNCE_MS = 1000;

const HEADER =
	"# Generated by NginxionS from its database (WAF settings of proxy hosts). Manual changes are overwritten.\n";

const MODES = ["detect-learn", "prevent-learn"];
const CONFIDENCES = ["medium", "high", "critical"];

/**
 * The policy to write: built from the objects (objects/store.js), the expert fragment merged over it, in v1beta2.
 * @param   {{custom?: object, candidate?: object}} [options]  parsed expert fragment instead of the one
 *   in force; objects, default policy or objects of hosts instead of the stored ones (store.buildDoc)
 * @returns {Promise<{policy: object, doc: object, hosts: number, customId: number|null,
 *   format: "v1beta1"|"v1beta2", reasons: string[], warnings: string[]}>}
 */
const buildPolicy = async ({ custom, candidate } = {}) => {
	const { doc, hosts } = await buildDoc(candidate);
	let merged = doc;
	let customId = null;
	if (custom) {
		merged = mergeCustom(doc, custom);
	} else {
		const current = await getCurrentCustom();
		if (current) {
			try {
				const parsed = parseCustom(current.content);
				if (Object.keys(parsed).length) {
					merged = mergeCustom(doc, parsed);
					customId = current.id;
				}
			} catch (err) {
				// validated when saved; only a hand-edited database gets here
				logger.error(`WAF: expert policy version ${current.id} is not applied: ${err.message}`);
			}
		}
	}
	const appsec = appsecRules(merged);
	const stored = new Set((await listSchemas().catch(() => [])).map((f) => f.name));
	return {
		// the engines CrowdSec runs (antiBot, schemaValidation) and File Security are off for the agent
		policy: asV2(forAgent(merged)),
		appsec,
		doc: merged,
		hosts,
		customId,
		format: "v1beta2",
		// kept for the clients of the API: why the file is v1beta2 (it always is)
		reasons: [],
		warnings: [
			// names the agent will not find (an expert fragment refers to a renamed or deleted object)
			...danglingRefs(merged).map((ref) => `missing:${ref}`),
			// the agent takes the first practice or trigger of a list
			...extraRefs(merged).map((ref) => `extra:${ref}`),
			// an OpenAPI file of schemaValidation NginxionS does not have (deleted, or an imported policy)
			...schemaFiles(appsec)
				.filter((f) => !stored.has(f))
				.map((f) => `schema-missing:${f}`),
			// engines saved before they were refused (docs/WAF-POLICY.md): the agent does nothing with them
			...(merged.threatPreventionPractices || []).flatMap((p) =>
				UNSUPPORTED_ENGINES.filter((e) => p[e]?.overrideMode && p[e].overrideMode !== "inactive").map(
					(e) => `unsupported:${p.name}:${e}`,
				),
			),
		],
	};
};

const parseJson = (value) => (typeof value === "string" ? JSON.parse(value) : value) || [];

const CUSTOM_HEADER = "# + expert fragments (WAF -> Policy), merged over the generated rules.\n";

const render = (policy, withCustom = false) =>
	`${HEADER}${withCustom ? CUSTOM_HEADER : ""}${YAML.stringify(policy, { lineWidth: 0, aliasDuplicateObjects: false })}`;

const readPolicyFile = async () => {
	try {
		return await readFile(POLICY_FILE, "utf8");
	} catch (err) {
		if (err.code === "ENOENT") {
			return null;
		}
		throw err;
	}
};

const backup = async (content, label) => {
	await mkdir(BACKUP_DIR, { recursive: true });
	const stamp = new Date().toISOString().replace(/[:.]/g, "-");
	await writeFile(`${BACKUP_DIR}/local_policy-${stamp}${label ? `-${label}` : ""}.yaml`, content, { mode: 0o600 });
	const files = (await readdir(BACKUP_DIR)).filter((f) => f.startsWith("local_policy-")).sort();
	for (const old of files.slice(0, Math.max(0, files.length - BACKUPS_KEPT))) {
		await rm(`${BACKUP_DIR}/${old}`, { force: true });
	}
};

// written in place of the old file by rename, so the agent never reads a half-written policy
const writeAtomic = async (content) => {
	await mkdir(dirname(POLICY_FILE), { recursive: true });
	const tmp = `${POLICY_FILE}.nginxions-tmp`;
	await writeFile(tmp, content, { mode: 0o644 });
	await rename(tmp, POLICY_FILE);
};

// the policy generated last (objects/format.js terms) and when the file last changed: checked against what the
// agent applies (applied.js)
let lastDoc = null;
let lastChangedAt = null;
export const getLastPolicy = () => ({ doc: lastDoc, changedAt: lastChangedAt });

const state = {
	generatedAt: null,
	hosts: 0,
	format: null,
	reasons: [],
	warnings: [],
	applied: null,
};

/**
 * Asks the agent to apply the policy now. Not reaching the agent is not an error of the change:
 * it applies the file at its next start or within 30 s (autoPolicyLoad).
 */
const notifyAgent = async () => {
	try {
		const response = await fetch(`${AGENT_URL}/set-apply-policy`, {
			method: "POST",
			headers: { "Content-Type": "application/json" },
			body: JSON.stringify({ policy_path: AGENT_POLICY_PATH }),
			signal: AbortSignal.timeout(APPLY_TIMEOUT_MS),
		});
		state.applied = {
			ok: response.ok,
			at: new Date().toISOString(),
			error: response.ok ? null : `HTTP ${response.status}`,
		};
	} catch (err) {
		state.applied = { ok: false, at: new Date().toISOString(), error: err.cause?.code || err.message };
	}
	if (!state.applied.ok) {
		logger.warn(`WAF policy written, the agent was not notified (${state.applied.error})`);
		retryNotify();
	}
	return state.applied;
};

// the agent starts after nginxions (it joins its network namespace): ask again for a while, so that the
// state in the GUI is not "not applied" until the next change
const NOTIFY_RETRIES = 8;
const NOTIFY_RETRY_MS = 15000;
let retries = 0;
let retryTimer = null;
function retryNotify() {
	if (retryTimer || retries >= NOTIFY_RETRIES) return;
	retries++;
	retryTimer = setTimeout(async () => {
		retryTimer = null;
		if ((await notifyAgent()).ok) retries = 0;
	}, NOTIFY_RETRY_MS);
	retryTimer.unref?.();
}

/**
 * Generates local_policy.yaml from the database; writes it (with a backup of the previous
 * version) and notifies the agent only if it changed, unless forced.
 * @param   {{force?: boolean}} [options]
 * @returns {Promise<{changed: boolean, hosts: number}>}
 */
const regenerate = async ({ force = false } = {}) => {
	const { policy, appsec, doc, hosts, customId, format, reasons, warnings } = await buildPolicy();
	const content = render(policy, customId !== null);
	const current = await readPolicyFile();
	const changed = current !== content;
	if (changed) {
		if (current !== null) {
			await backup(current);
		}
		await writeAtomic(content);
		logger.info(`WAF policy generated: ${hosts} protected host(s)`);
		lastChangedAt = new Date().toISOString();
	}
	lastDoc = doc;
	state.generatedAt = new Date().toISOString();
	state.hosts = hosts;
	state.format = format;
	state.reasons = reasons;
	state.warnings = warnings;
	if (changed || force) {
		retries = 0;
		await notifyAgent();
	}
	// File Security: the hosts that check uploads with ClamAV, and clamd itself
	try {
		await applyFiles(doc);
	} catch (err) {
		logger.error(`WAF: File Security was not applied: ${err.message}`);
	}
	// antiBot and schemaValidation run in AppSec of CrowdSec: its appsec-config follows the policy
	if (setEngines(appsec)) {
		const { applyPolicyEngines } = await import("../crowdsec/index.js");
		applyPolicyEngines().catch((err) =>
			logger.error(`WAF: the engines of CrowdSec were not applied: ${err.message}`),
		);
	}
	return { changed, hosts };
};

// one generation at a time; a burst of changes (e.g. regenerating all hosts) ends in one write
let timer = null;
let running = Promise.resolve();
const scheduleRegenerate = () => {
	clearTimeout(timer);
	timer = setTimeout(() => {
		running = running
			.then(() => regenerate())
			.catch((err) => logger.error(`WAF policy generation failed: ${err.message}`));
	}, DEBOUNCE_MS);
	timer.unref?.();
};

/**
 * Regenerates now (waits for a pending scheduled run first).
 * @param {{force?: boolean}} [options]
 */
const regenerateNow = (options) => {
	clearTimeout(timer);
	const result = running.then(() => regenerate(options));
	running = result.catch(() => {});
	return result;
};

/**
 * Migration from open-appsec-npm: if NginxionS has no WAF settings yet, takes them from the
 * npm-managed-* rules of an existing local_policy.yaml. The original file is kept in the backups.
 * @param {string} content
 */
const importLegacy = async (content) => {
	let policy;
	try {
		policy = YAML.parse(content);
	} catch (err) {
		logger.warn(`WAF: existing local_policy.yaml is not valid YAML, not imported (${err.message})`);
		return 0;
	}
	const rules = policy?.policies?.["specific-rules"];
	if (!Array.isArray(rules)) {
		return 0;
	}
	const practices = _.keyBy(Array.isArray(policy.practices) ? policy.practices : [], "name");
	const knex = db();
	const now = new Date();
	let imported = 0;
	for (const rule of rules) {
		const match = /^npm-managed-specific-rule-proxyhost-(\d+)(?:-(\d+))?$/.exec(rule?.name || "");
		if (!match) {
			continue;
		}
		const hostId = Number.parseInt(match[1], 10);
		const proxyHost = await knex("proxy_host")
			.select("id", "locations")
			.where({ id: hostId, is_deleted: 0 })
			.first();
		if (!proxyHost) {
			continue;
		}
		const enabled = MODES.includes(rule.mode);
		const confidence = practices[rule.practices?.[0]]?.["web-attacks"]?.["minimum-confidence"];
		const values = {
			enabled,
			mode: enabled ? rule.mode : "detect-learn",
			minimum_confidence: CONFIDENCES.includes(confidence) ? confidence : "high",
			modified_on: now,
		};
		if (match[2] === undefined) {
			await knex("nginxions_waf_host")
				.insert({ proxy_host_id: hostId, ...values })
				.onConflict("proxy_host_id")
				.merge();
		} else {
			const path = parseJson(proxyHost.locations)[Number.parseInt(match[2], 10)]?.path;
			if (!path) {
				continue;
			}
			await knex("nginxions_waf_location")
				.insert({ proxy_host_id: hostId, path, ...values })
				.onConflict(["proxy_host_id", "path"])
				.merge();
		}
		imported++;
	}
	return imported;
};

/**
 * At backend start: import from open-appsec-npm on the first start, then generate the policy.
 * Never blocks the start of NginxionS: errors are logged and shown in the GUI.
 */
const bootstrap = async () => {
	try {
		const current = await readPolicyFile();
		if (current !== null && !current.startsWith(HEADER)) {
			await backup(current, "before-nginxions");
			const { count } = await db()("nginxions_waf_host").count("proxy_host_id as count").first();
			if (Number(count) === 0) {
				const imported = await importLegacy(current);
				if (imported) {
					logger.info(`WAF: imported ${imported} rule(s) from open-appsec-npm`);
				}
			}
		}
		await seedBuiltins();
		await regenerateNow({ force: true });
	} catch (err) {
		logger.error(`WAF policy bootstrap failed: ${err.message}`);
		debug(logger, err);
	}
};

const getPolicyState = () => ({ file: POLICY_FILE, ...state });

export {
	bootstrap,
	buildPolicy,
	CONFIDENCES,
	getPolicyState,
	importLegacy,
	MODES,
	readPolicyFile,
	regenerateNow,
	render,
	scheduleRegenerate,
};
