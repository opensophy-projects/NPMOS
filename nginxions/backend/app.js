import crypto from "node:crypto";
import { readFileSync } from "node:fs";
import cookieParser from "cookie-parser";
import express from "express";
import { DBError } from "objection";
import fileUpload from "express-fileupload";
import { debug, express as logger } from "./logger.js";
import mainRoutes from "./routes/main.js";

/**
 * App
 */
const app = express();

app.enable("trust proxy");
app.use((req, _res, next) => {
	req.headers["x-forwarded-for"] = req.header("x-real-ip");
	return next();
});

app.disable("x-powered-by");
app.set("json spaces", 2);

// NginxionS: answers of the API (tokens, settings, keys) are not stored by browsers or proxies; a route that may be
// cached (CRL, OCSP of the PKI) sets its own Cache-Control (DAST: ZAP 10015, 10049; ZAP wants no-cache and
// must-revalidate next to no-store, for caches that do not know no-store)
app.use((_req, res, next) => {
	res.set("Cache-Control", "no-cache, no-store, must-revalidate");
	next();
});

app.use(
	fileUpload({
		limits: { fileSize: 1024 * 1024 },
	}),
);
// NginxionS: COOKIE_SECRET_FILE (generated by nginxions-init) keeps sessions valid across restarts
const cookieSecret = process.env.COOKIE_SECRET_FILE
	? readFileSync(process.env.COOKIE_SECRET_FILE, "utf8").trim()
	: process.env.COOKIE_SECRET;
app.use(cookieParser(cookieSecret || crypto.randomBytes(16).toString("hex")));
app.use(express.json());
app.use(express.urlencoded({ extended: true }));

/**
 * General Logging, BEFORE routes
 */

app.use((req, res, next) => {
	if (
		req.method === "GET" &&
		req.path === "/api/oidc/callback" &&
		req.get("sec-fetch-mode") === "navigate" &&
		req.get("sec-fetch-dest") === "document"
	) {
		return next();
	}

	if (req.get("origin") && req.get("origin") !== `${req.protocol}://${req.host}`) {
		return res.status(403).json({
			error: { message: "Rejected Origin." },
		});
	}
	if (["same-origin", "none", undefined].includes(req.get("sec-fetch-site"))) {
		return next();
	}

	res.status(403).json({
		error: { message: "Rejected Sec-Fetch-Site Value." },
	});
});

app.use("/", mainRoutes);

// production error handler
// no stacktraces leaked to user
app.use((err, req, res, _) => {
	// NginxionS: a bad ?expand= (not a relation of the object) is a bad request of the client, not an internal error
	// (objection: ValidationError, statusCode 400; DAST: ZAP answered 500 to ?expand=http://...)
	if (!err.status && err.name === "ValidationError" && err.statusCode === 400) {
		err.status = 400;
		err.public = true;
	}
	// NginxionS: the database refusing the data of a request (an id of a certificate or access list that does not exist,
	// a value of a wrong type, a duplicate) is a bad request too, not an internal error (DAST: ZAP got 500 on POST and PUT
	// of hosts); the message of the database is not shown
	if (!err.status && err instanceof DBError) {
		err.status = 400;
	}
	const payload = {
		error: {
			code: err.status || 500,
			message: err.public ? err.message : "Internal Error",
		},
	};

	if (typeof err.message_i18n !== "undefined") {
		payload.error.message_i18n = err.message_i18n;
	}

	if ((req.baseUrl + req.originalUrl).includes("nginx/certificates")) {
		payload.debug = {
			stack: typeof err.stack !== "undefined" && err.stack ? err.stack.split("\n") : null,
			previous: err.previous,
		};
	}

	// Not every error is worth logging - but this is good for now until it gets annoying.
	if (typeof err.stack !== "undefined" && err.stack) {
		debug(logger, err.stack);
		if (typeof err.public === "undefined" || !err.public) {
			logger.warn(`${req.method.toUpperCase()} ${req.originalUrl}: ${err}`);
		}
	}

	res.status(err.status || 500).send(payload);
});

export default app;
